import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const industryPath = path.resolve(here, "../../src/qenivo/models/industry.py");
const outPath = path.resolve(here, "../src/lib/manifest.ts");

const text = fs.readFileSync(industryPath, "utf8").replace(/\r\n/g, "\n");
const docStart = text.indexOf('"""');
const docEnd = text.indexOf('"""', docStart + 3);
if (docStart < 0 || docEnd < 0) throw new Error("industry.py module docstring not found");

const meta = new Map();
let previous = null;
for (const line of text.slice(docStart + 3, docEnd).split("\n")) {
  const parts = line.trim().split(/\s{2,}/);
  if (parts.length >= 4 && /^(LP|QP|MILP)$/.test(parts[2]) && /^[A-Za-z_][A-Za-z0-9_]*$/.test(parts[1])) {
    previous = {
      sector: parts[0],
      problemClass: parts[2],
      formulation: parts.slice(3).join("  "),
    };
    meta.set(parts[1], previous);
    continue;
  }
  if (previous && /^\s{10,}\S/.test(line)) {
    previous.formulation = `${previous.formulation} ${line.trim()}`.replace(/\s+/g, " ");
  }
}

const libraryBlock = text.match(/\nLIBRARY\s*=\s*\{([\s\S]*?)\n\}/);
if (!libraryBlock) throw new Error("LIBRARY dict not found in industry.py");
const names = [...libraryBlock[1].matchAll(/"([A-Za-z_][A-Za-z0-9_]*)"\s*:/g)].map((m) => m[1]);
if (names.length === 0) throw new Error("LIBRARY dict has no names");

function parseParams(list) {
  const out = [];
  for (const part of list.split(",")) {
    const piece = part.trim();
    if (!piece) continue;
    const eq = piece.indexOf("=");
    if (eq < 0) out.push({ name: piece.split(":")[0].trim(), default: "" });
    else out.push({ name: piece.slice(0, eq).trim(), default: piece.slice(eq + 1).trim() });
  }
  return out;
}

const models = names.map((name) => {
  const found = text.match(new RegExp(`^def ${name}\\(([^)]*)\\)[^\\n]*\\n\\s+"""([\\s\\S]*?)"""`, "m"));
  if (!found) throw new Error(`no docstring for ${name}`);
  const info = meta.get(name);
  if (!info) throw new Error(`no sector row for ${name} in the industry.py header table`);
  const detail = found[2].trim().replace(/\s+/g, " ");
  const summary = detail;
  const parameters = parseParams(found[1]);
  const flags = parameters.map((p) => `-p ${p.name}=${p.default}`).join(" ");
  const command = `qenivo model ${name}${flags ? ` ${flags}` : ""} -o ${name}.mps`;
  return {
    name,
    sector: info.sector,
    problemClass: info.problemClass,
    formulation: info.formulation,
    summary,
    detail,
    parameters,
    command,
  };
});

const body = `/* Generated by scripts/build-manifest.mjs from qenivo/src/qenivo/models/industry.py. */\nimport type { LibraryModel } from "./library.js";\n\nexport const library: LibraryModel[] = ${JSON.stringify(models, null, 2)};\n`;
fs.writeFileSync(outPath, body);
console.log(`wrote ${models.length} models to ${path.relative(process.cwd(), outPath)}`);
